def make_draft_id() -> str:
    return f"DRAFT-{datetime.now().strftime('%Y%m%d%H%M%S%f')}"


def drafts_df() -> pd.DataFrame:
    drafts = st.session_state.get("customer_drafts", [])
    if not drafts:
        return pd.DataFrame(columns=[
            "Draft ID", "Brand", "Platform", "Pillar", "Trend", "Hook", "Content", "CTA", "Offer", "Status",
            "Owner", "Due Date", "Created", "Updated", "Words", "Characters", "Score",
        ])
    return pd.DataFrame(drafts)


def render_crud_studio(df: pd.DataFrame, brands: List[str], query: str) -> None:
    active = filtered_rows(df, brands, query)
    render_hero(
        "CRUD Studio",
        "Create, review, update, duplicate, delete, and export customer content drafts inside this dashboard session without altering your existing source columns.",
        ["Create", "Read", "Update", "Delete", "Duplicate", "Export"],
    )

    tabs = st.tabs(["Create Draft", "Manage Drafts", "Import From Content Row", "Draft Metrics"])

    with tabs[0]:
        st.markdown("### Create Customer Content Draft")
        with st.form("create_draft_form", clear_on_submit=True):
            c1, c2, c3 = st.columns(3)
            with c1:
                brand = st.selectbox("Brand", sorted(BRAND_STRATEGY.keys()))
                platform = st.selectbox("Platform", CHANNEL_COLUMNS, format_func=lambda v: f"{PLATFORM_ICONS.get(v, '•')} {DISPLAY_NAMES.get(v, v)}")
                status = st.selectbox("Status", STATUS_ORDER, index=1)
            with c2:
                pillar_options = BRAND_STRATEGY.get(brand, {}).get("pillars", [])
                pillar = st.selectbox("Pillar", pillar_options if pillar_options else ["Customer Content"])
                owner = st.text_input("Owner", value=str(st.session_state.auth_name or "Team"))
                due_date = st.date_input("Due Date")
            with c3:
                offer_options = BRAND_STRATEGY.get(brand, {}).get("offers", [])
                offer = st.selectbox("Offer", offer_options if offer_options else ["Customer Offer"])
                trend = st.text_input("Trend / Topic", placeholder="Enter customer-facing topic")
                hook = st.text_input("Hook", placeholder="Enter first-line hook")
            content = st.text_area("Content", height=220, placeholder="Write or paste the post, email, script, or campaign copy...")
            cta = st.text_input("CTA", placeholder="Example: Save this, comment READY, book a call, download the checklist")
            submitted = st.form_submit_button("Create Draft", use_container_width=True)
        if submitted:
            now = datetime.now().strftime("%Y-%m-%d %I:%M %p")
            draft = {
                "Draft ID": make_draft_id(),
                "Brand": brand,
                "Platform": platform,
                "Pillar": pillar,
                "Trend": trend,
                "Hook": hook,
                "Content": content,
                "CTA": cta,
                "Offer": offer,
                "Status": status,
                "Owner": owner,
                "Due Date": str(due_date),
                "Created": now,
                "Updated": now,
                "Words": count_words(content),
                "Characters": len(content),
                "Score": min(10, 2 + min(3, count_words(content) // 70) + min(2, count_cta_terms(content) + count_cta_terms(cta)) + min(2, count_hook_terms(content) + count_hook_terms(hook)) + min(1, len(extract_hashtags(content)))),
            }
            st.session_state.customer_drafts.append(draft)
            st.success("Draft created.")

    with tabs[1]:
        current = drafts_df()
        st.markdown("### Manage Customer Drafts")
        if current.empty:
            st.info("No session drafts yet. Create one or import from an existing content row.")
        else:
            c1, c2, c3 = st.columns(3)
            with c1:
                status_filter = st.multiselect("Status Filter", STATUS_ORDER, default=STATUS_ORDER)
            with c2:
                brand_filter = st.multiselect("Draft Brand Filter", sorted(current["Brand"].unique()), default=sorted(current["Brand"].unique()))
            with c3:
                platform_filter = st.multiselect("Draft Platform Filter", sorted(current["Platform"].unique()), default=sorted(current["Platform"].unique()))
            filtered = current[
                current["Status"].isin(status_filter)
                & current["Brand"].isin(brand_filter)
                & current["Platform"].isin(platform_filter)
            ].copy()
            st.dataframe(filtered, use_container_width=True, hide_index=True)

            selected_id = st.selectbox("Select draft to edit", filtered["Draft ID"].tolist() if not filtered.empty else current["Draft ID"].tolist())
            draft_index = next((i for i, item in enumerate(st.session_state.customer_drafts) if item["Draft ID"] == selected_id), None)
            if draft_index is not None:
                draft = st.session_state.customer_drafts[draft_index]
                with st.form("update_draft_form"):
                    c1, c2, c3 = st.columns(3)
                    with c1:
                        new_brand = st.selectbox("Edit Brand", sorted(BRAND_STRATEGY.keys()), index=sorted(BRAND_STRATEGY.keys()).index(draft["Brand"]) if draft["Brand"] in sorted(BRAND_STRATEGY.keys()) else 0)
                        new_platform = st.selectbox("Edit Platform", CHANNEL_COLUMNS, index=CHANNEL_COLUMNS.index(draft["Platform"]) if draft["Platform"] in CHANNEL_COLUMNS else 0, format_func=lambda v: f"{PLATFORM_ICONS.get(v, '•')} {DISPLAY_NAMES.get(v, v)}")
                        new_status = st.selectbox("Edit Status", STATUS_ORDER, index=STATUS_ORDER.index(draft["Status"]) if draft["Status"] in STATUS_ORDER else 1)
                    with c2:
                        pillar_options = BRAND_STRATEGY.get(new_brand, {}).get("pillars", [])
                        new_pillar = st.selectbox("Edit Pillar", pillar_options if pillar_options else [draft.get("Pillar", "Customer Content")], index=0)
                        new_owner = st.text_input("Edit Owner", value=draft.get("Owner", "Team"))
                        new_due_date = st.text_input("Edit Due Date", value=str(draft.get("Due Date", "")))
                    with c3:
                        offer_options = BRAND_STRATEGY.get(new_brand, {}).get("offers", [])
                        existing_offer = draft.get("Offer", "")
                        offer_index = offer_options.index(existing_offer) if existing_offer in offer_options else 0
                        new_offer = st.selectbox("Edit Offer", offer_options if offer_options else [existing_offer or "Customer Offer"], index=offer_index)
                        new_trend = st.text_input("Edit Trend / Topic", value=draft.get("Trend", ""))
                        new_hook = st.text_input("Edit Hook", value=draft.get("Hook", ""))
                    new_content = st.text_area("Edit Content", value=draft.get("Content", ""), height=260)
                    new_cta = st.text_input("Edit CTA", value=draft.get("CTA", ""))
                    update_btn = st.form_submit_button("Update Draft", use_container_width=True)
                if update_btn:
                    now = datetime.now().strftime("%Y-%m-%d %I:%M %p")
                    st.session_state.customer_drafts[draft_index].update({
                        "Brand": new_brand,
                        "Platform": new_platform,
                        "Pillar": new_pillar,
                        "Trend": new_trend,
                        "Hook": new_hook,
                        "Content": new_content,
                        "CTA": new_cta,
                        "Offer": new_offer,
                        "Status": new_status,
                        "Owner": new_owner,
                        "Due Date": new_due_date,
                        "Updated": now,
                        "Words": count_words(new_content),
                        "Characters": len(new_content),
                        "Score": min(10, 2 + min(3, count_words(new_content) // 70) + min(2, count_cta_terms(new_content) + count_cta_terms(new_cta)) + min(2, count_hook_terms(new_content) + count_hook_terms(new_hook)) + min(1, len(extract_hashtags(new_content)))),
                    })
                    st.success("Draft updated.")
                    st.rerun()

                d1, d2 = st.columns(2)
                if d1.button("Duplicate Selected Draft", use_container_width=True):
                    new_draft = dict(draft)
                    new_draft["Draft ID"] = make_draft_id()
                    new_draft["Trend"] = f"{new_draft.get('Trend', '')} Copy".strip()
                    new_draft["Created"] = datetime.now().strftime("%Y-%m-%d %I:%M %p")
                    new_draft["Updated"] = new_draft["Created"]
                    st.session_state.customer_drafts.append(new_draft)
                    st.success("Draft duplicated.")
                    st.rerun()
                if d2.button("Delete Selected Draft", use_container_width=True):
                    st.session_state.customer_drafts = [item for item in st.session_state.customer_drafts if item["Draft ID"] != selected_id]
                    st.success("Draft deleted.")
                    st.rerun()

            export = drafts_df()
            st.download_button(
                "Download Session Drafts CSV",
                data=export.to_csv(index=False).encode("utf-8"),
                file_name="customer_brand_session_drafts.csv",
                mime="text/csv",
                use_container_width=True,
            )

    with tabs[2]:
        st.markdown("### Import Existing Content Row Into Drafts")
        if active.empty:
            st.info("No active rows match current filters.")
        else:
            import_table = active[["Row", "Brand", "Pillar", "Trend", "Hook", "Offer", "Readiness", "Opportunity Score"]].copy()
            st.dataframe(import_table, use_container_width=True, hide_index=True)
            selected_row = st.selectbox("Choose row", active["Row"].tolist())
            selected_platform = st.selectbox("Choose platform to import", CHANNEL_COLUMNS, format_func=lambda v: f"{PLATFORM_ICONS.get(v, '•')} {DISPLAY_NAMES.get(v, v)}")
            if st.button("Import Selected Row As Draft", use_container_width=True):
                row = active[active["Row"] == selected_row].iloc[0]
                content = str(row.get(selected_platform, "")).strip()
                if not content:
                    st.error("Selected platform is empty for this row.")
                else:
                    now = datetime.now().strftime("%Y-%m-%d %I:%M %p")
                    draft = {
                        "Draft ID": make_draft_id(),
                        "Brand": row.get("Brand", ""),
                        "Platform": selected_platform,
                        "Pillar": row.get("Pillar", ""),
                        "Trend": row.get("Trend", ""),
                        "Hook": row.get("Hook", ""),
                        "Content": content,
                        "CTA": row.get("CTA", ""),
                        "Offer": row.get("Offer", ""),
                        "Status": row.get("Readiness", "Draft"),
                        "Owner": str(st.session_state.auth_name or "Team"),
                        "Due Date": "",
                        "Created": now,
                        "Updated": now,
                        "Words": count_words(content),
                        "Characters": len(content),
                        "Score": int(row.get("Opportunity Score", 0) or 0),
                    }
                    st.session_state.customer_drafts.append(draft)
                    st.success("Content imported into drafts.")

    with tabs[3]:
        current = drafts_df()
        st.markdown("### Draft Metrics")
        if current.empty:
            st.info("No drafts to measure yet.")
        else:
            c1, c2, c3, c4, c5 = st.columns(5)
            c1.metric("Drafts", len(current))
            c2.metric("Ready", int((current["Status"] == "Ready").sum()))
            c3.metric("Words", f"{int(current['Words'].sum()):,}")
            c4.metric("Avg Score", round(float(current["Score"].mean()), 1))
            c5.metric("Platforms", current["Platform"].nunique())
            st.markdown("### Drafts by Status")
            st.bar_chart(current["Status"].value_counts().reindex(STATUS_ORDER, fill_value=0))
            st.markdown("### Drafts by Platform")
            st.bar_chart(current["Platform"].value_counts())


