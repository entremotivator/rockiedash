def first_line(value: Any, max_chars: int = 95) -> str:
    text = re.sub(r"\s+", " ", str(value or "")).strip()
    if not text:
        return ""
    line = text.split(".")[0].strip() or text
    return line[:max_chars].rstrip() + ("…" if len(line) > max_chars else "")


def extract_hashtags(text: Any) -> List[str]:
    return sorted(set(re.findall(r"#[A-Za-z0-9_]+", str(text or ""))))


def count_words(text: Any) -> int:
    return len(re.findall(r"\b\w+\b", str(text or "")))


def score_text(row: pd.Series) -> int:
    blob = " ".join(str(row.get(c, "")) for c in CHANNEL_COLUMNS)
    filled = sum(1 for c in CHANNEL_COLUMNS if str(row.get(c, "")).strip())
    keyword_bonus = sum(1 for k in ["client", "marketing", "student", "business", "school", "content", "brand", "confidence", "search", "offer", "beauty", "cosmetology"] if k in blob.lower())
    return min(10, 2 + min(4, filled // 2) + min(3, len(blob) // 1400) + min(1, keyword_bonus // 4))


def infer_primary_topic(row: pd.Series) -> str:
    for col in ["Trend", "Topic", "Title", "Research Strategy", "Blog", "Blog (AI Agent)", "IG", "Tiktok", "Linkedin", "Facebook"]:
        candidate = str(row.get(col, "")).strip()
        if candidate:
            return first_line(candidate)
    return "Google Sheets content row"


