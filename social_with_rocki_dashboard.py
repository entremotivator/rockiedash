def filtered_rows(df: pd.DataFrame, brands: List[str], query: str) -> pd.DataFrame:
    active = df[df["Brand"].isin(brands)].copy() if brands else df.copy()
    if query.strip() and not active.empty:
        cols = ["Brand", "Source Sheet", "Pillar", "Trend", "Hook", "CTA", "Offer"] + CHANNEL_COLUMNS
        available = [c for c in cols if c in active.columns]
        mask = active[available].apply(lambda c: c.astype(str).str.contains(query.strip(), case=False, na=False))
        active = active[mask.any(axis=1)]
    return active.reset_index(drop=True)


