def render_app() -> None:
    df, status_df = load_content_streams()
    page, brands, platforms, query = render_sidebar(df)

    if page == "Dashboard":
        render_dashboard(df, status_df, brands, platforms, query)
    elif page == "Customer Brand":
        render_customer_brand(df, brands, query)
    elif page == "Analytics":
        render_analytics(df, brands, platforms, query)
    elif page == "Trend Finder":
        render_trend_finder(filtered_rows(df, brands, query))
    elif page == "Content Library":
        render_content_library(df, brands, platforms, query)
    elif page == "Content Calendar":
        render_calendar(df, brands, query)
    elif page == "CRUD Studio":
        render_crud_studio(df, brands, query)
    elif page == "Export Center":
        render_export_center(df, brands, platforms, query)
    else:
        render_source_health(status_df)


