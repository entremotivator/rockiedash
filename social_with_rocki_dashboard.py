def normalize_sheet(df: pd.DataFrame, source: Dict[str, str]) -> pd.DataFrame:
    frame = df.copy()
    frame.columns = [str(c).strip() for c in frame.columns]

    for col in CHANNEL_COLUMNS:
        if col not in frame.columns:
            frame[col] = ""
    for col in source["expected_columns"]:
        if col not in frame.columns:
            frame[col] = ""

    if "Brand" not in frame.columns:
        frame["Brand"] = source["brand"]
    frame["Brand"] = frame["Brand"].fillna("").replace("", source["brand"])

    frame = frame.fillna("").astype(str)
    frame["Source Sheet"] = source["sheet_name"]
    frame["Source GID"] = source["gid"]
    frame["Source URL"] = google_csv_url(source["gid"])
    frame["Source Row"] = range(2, len(frame) + 2)
    frame["Trend"] = frame.apply(infer_primary_topic, axis=1)
    if "Pillar" not in frame.columns:
        frame["Pillar"] = ""
    frame["Pillar"] = frame.apply(lambda r: r.get("Pillar") or infer_pillar(str(r.get("Brand", source["brand"])), str(r.get("Trend", ""))), axis=1)
    frame["Hook"] = frame.apply(lambda r: first_line(r.get("IG") or r.get("Tiktok") or r.get("Linkedin") or r.get("Blog") or r.get("Research Strategy")), axis=1)
    frame["Search Intent"] = frame.apply(lambda r: f"Imported from {source['sheet_name']} Google Sheet", axis=1)
    frame["Target Audience"] = frame["Brand"].map(lambda b: BRAND_STRATEGY.get(b, BRAND_STRATEGY[source["brand"]])["audience"])
    frame["CTA"] = frame.apply(lambda r: "Copy, repurpose, schedule, or turn into a lead magnet.", axis=1)
    frame["Offer"] = frame["Brand"].map(lambda b: BRAND_STRATEGY.get(b, BRAND_STRATEGY[source["brand"]])["offers"][0])
    frame["Content Pieces"] = frame[CHANNEL_COLUMNS].apply(lambda r: int(r.astype(str).str.strip().ne("").sum()), axis=1)
    frame["Total Words"] = frame[CHANNEL_COLUMNS].apply(lambda r: sum(count_words(v) for v in r), axis=1)
    frame["Opportunity Score"] = frame.apply(score_text, axis=1)
    return frame


def load_google_sheets_only() -> Tuple[pd.DataFrame, pd.DataFrame]:
    frames = []
    status_rows = []
    using_private = has_service_account()

    for source in SHEET_SOURCES:
        try:
            if using_private:
                raw = read_private_sheet(source["gid"])
                mode = "Private service account"
            else:
                raw = read_public_sheet(source["gid"])
                mode = "Public CSV export"
            normalized = normalize_sheet(raw, source)
            frames.append(normalized)
            missing = [c for c in source["expected_columns"] if c not in raw.columns]
            status_rows.append({
                "Brand": source["brand"],
                "Sheet": source["sheet_name"],
                "GID": source["gid"],
                "Mode": mode,
                "Rows Pulled": len(raw),
                "Expected Columns": ", ".join(source["expected_columns"]),
                "Missing Expected Columns": ", ".join(missing) if missing else "None",
                "Status": "Connected",
                "Message": source["description"],
            })
        except Exception as exc:
            status_rows.append({
                "Brand": source["brand"],
                "Sheet": source["sheet_name"],
                "GID": source["gid"],
                "Mode": "Private service account" if using_private else "Public CSV export",
                "Rows Pulled": 0,
                "Expected Columns": ", ".join(source["expected_columns"]),
                "Missing Expected Columns": "Unknown",
                "Status": "Not connected",
                "Message": str(exc),
            })

    if frames:
        data = pd.concat(frames, ignore_index=True)
        data["Row"] = range(1, len(data) + 1)
    else:
        data = pd.DataFrame(columns=["Row", "Brand", "Source Sheet", "Source GID", "Source URL", "Source Row", "Trend", "Pillar", "Hook", "Search Intent", "Target Audience", "CTA", "Offer", "Content Pieces", "Total Words", "Opportunity Score"] + CHANNEL_COLUMNS)
    return data, pd.DataFrame(status_rows)


def build_long_df(df: pd.DataFrame) -> pd.DataFrame:
    rows = []
    for _, row in df.iterrows():
        for column in CHANNEL_COLUMNS:
            content = str(row.get(column, "")).strip()
            if content:
                rows.append({
                    "Row": row.get("Row", ""),
                    "Brand": row.get("Brand", ""),
                    "Source Sheet": row.get("Source Sheet", ""),
                    "Source Row": row.get("Source Row", ""),
                    "Platform Key": column,
                    "Platform": DISPLAY_NAMES.get(column, column),
                    "Pillar": row.get("Pillar", ""),
                    "Trend": row.get("Trend", ""),
                    "Hook": row.get("Hook", ""),
                    "CTA": row.get("CTA", ""),
                    "Offer": row.get("Offer", ""),
                    "Content": content,
                    "Characters": len(content),
                    "Words": count_words(content),
                    "Hashtags": ", ".join(extract_hashtags(content)),
                    "Opportunity Score": int(row.get("Opportunity Score", 0) or 0),
                })
    return pd.DataFrame(rows)


