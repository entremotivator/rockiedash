def render_app() -> None:
    df, status_df = load_google_sheets_only()
    page, brands, platforms, query = render_sidebar(df)
    if page == "Dashboard":
        render_dashboard(df, status_df, brands, platforms, query)
    elif page == "Google Sheets Source":
        render_source_status(status_df)
    elif page == "Social With Rocki":
        render_brand_page(df, "Social With Rocki")
    elif page == "Cosmetology With Rocki":
        render_brand_page(df, "Cosmetology With Rocki")
    elif page == "Trend Finder":
        render_trend_finder(df)
    elif page == "Social Content Library":
        render_social_library(df, brands, platforms, query)
    else:
        render_calendar(filtered_rows(df, brands, query))


