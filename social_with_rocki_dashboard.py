def safe_html(value: Any) -> str:
    return escape(str(value or ""))


def _hash_password(password: str) -> str:
    return hashlib.sha256(password.encode("utf-8")).hexdigest()


def _init_state() -> None:
    defaults = {"auth_ok": False, "auth_user": None, "auth_name": None, "auth_role": None}
    for key, value in defaults.items():
        if key not in st.session_state:
            st.session_state[key] = value


USERS = {
    "rocki": {"name": "Rocki", "role": "Content Studio Admin", "password_hash": _hash_password("rocki2026")},
    "admin": {"name": "Admin", "role": "Content Studio Admin", "password_hash": _hash_password("rocki2026")},
}


def _check_login(username: str, password: str) -> bool:
    record = USERS.get((username or "").strip().lower())
    return bool(record and record["password_hash"] == _hash_password(password or ""))


def _sign_in(username: str) -> None:
    record = USERS.get(username.strip().lower(), USERS["rocki"])
    st.session_state.auth_ok = True
    st.session_state.auth_user = username.strip().lower()
    st.session_state.auth_name = record["name"]
    st.session_state.auth_role = record["role"]


def _sign_out() -> None:
    for key in ["auth_ok", "auth_user", "auth_name", "auth_role"]:
        st.session_state[key] = False if key == "auth_ok" else None
    st.rerun()


def google_csv_url(gid: str) -> str:
    return f"https://docs.google.com/spreadsheets/d/{SPREADSHEET_ID}/export?format=csv&gid={gid}"


def has_service_account() -> bool:
    try:
        return bool(st.secrets.get("gcp_service_account")) and gspread is not None and Credentials is not None
    except Exception:
        return False


def read_private_sheet(gid: str) -> pd.DataFrame:
    scopes = ["https://www.googleapis.com/auth/spreadsheets.readonly"]
    creds = Credentials.from_service_account_info(dict(st.secrets["gcp_service_account"]), scopes=scopes)
    client = gspread.authorize(creds)
    workbook = client.open_by_key(SPREADSHEET_ID)
    worksheet = workbook.get_worksheet_by_id(int(gid))
    values = worksheet.get_all_values()
    if not values:
        return pd.DataFrame()
    headers = values[0]
    return pd.DataFrame(values[1:], columns=headers)


